#!/usr/bin/env python3
"""Generate label and display-kind tables from ontology/ (standard library only).

  python3 tools/design_codegen.py [--check]

Writes src/generated/labels.ts from ontology/labels.yaml and src/generated/display.ts from the
`display` key of ontology/entities/*.yaml. --check fails when the files are out of date.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo_ontology import load_entities, load_yaml_file

ROOT = Path(__file__).resolve().parent.parent
DISPLAY_KINDS = (
    "money",
    "area",
    "count",
    "date",
    "datetime",
    "person",
    "phone",
    "status",
    "text",
    "boolean",
    "select",
)
RIGHT_ALIGNED = ("money", "area", "count")
# Entities shown on a screen: every property states how it is displayed, or that it is not.
DISPLAY_REQUIRED = {"Listing", "Unit"}
DISPLAY_EXEMPT = {"id", "companyId"}
HEADER = "// Generated by tools/design_codegen.py. Do not edit: change ontology/ and run `make gen`.\n"


def render_labels(concepts: dict) -> str:
    rows = []
    for code, concept in concepts.items():
        entry = {"pref": concept["pref"]}
        if concept.get("lease"):
            entry["lease"] = concept["lease"]
        rows.append(f"  {code}: {json.dumps(entry, ensure_ascii=False)},")
    return (
        HEADER
        + "export const LABELS = {\n"
        + "\n".join(rows)
        + "\n} as const;\n\nexport type ConceptCode = keyof typeof LABELS;\n"
    )


def collect_display(entities: dict) -> dict[str, str]:
    table: dict[str, str] = {}
    for name, entity in entities.items():
        for prop, spec in (entity.get("properties") or {}).items():
            kind = spec.get("display") if isinstance(spec, dict) else None
            if kind is None:
                if name in DISPLAY_REQUIRED and prop not in DISPLAY_EXEMPT:
                    raise SystemExit(f"{name}.{prop}: needs a display kind, or display: none")
                continue
            if kind == "none":
                continue
            if kind not in DISPLAY_KINDS:
                raise SystemExit(f"{name}.{prop}: unknown display kind '{kind}'")
            table[f"{name}.{prop}"] = kind
    return table


def render_display(table: dict[str, str]) -> str:
    kinds = " | ".join(json.dumps(k) for k in DISPLAY_KINDS)
    rows = "\n".join(f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in sorted(table.items()))
    right = ", ".join(json.dumps(k) for k in RIGHT_ALIGNED)
    return (
        HEADER
        + f"export type DisplayKind = {kinds};\n\n"
        + "export const FIELD_DISPLAY = {\n"
        + rows
        + "\n} as const satisfies Record<string, DisplayKind>;\n\n"
        + f"export const RIGHT_ALIGNED_KINDS: readonly DisplayKind[] = [{right}];\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    labels = load_yaml_file(ROOT / "ontology" / "labels.yaml")
    outputs = {
        ROOT / "src/generated/labels.ts": render_labels(labels["concepts"]),
        ROOT / "src/generated/display.ts": render_display(collect_display(load_entities(ROOT))),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text("utf-8") != text]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run make gen)")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
