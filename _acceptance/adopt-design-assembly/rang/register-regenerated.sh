#!/usr/bin/env bash
# AC-7: the old register tool is gone, make gen writes the component register with the
# design-assembly tool and make check checks it with that tool, and writing it again from the
# source gives the committed file. Stops at the first thing that is not so.
# Usage: bash register-regenerated.sh <repository>
set -u
root="${1:-.}"
mk="$root/mk/design.mk"

if [ -e "$root/tools/design_registry.mjs" ]; then
  echo "old tool still there"
  exit 1
fi
if ! grep -qF "node tools/design-assembly/components.mjs --write" "$mk"; then
  echo "make gen does not write the register with the design-assembly tool"
  exit 1
fi
if ! grep -qE "^[[:space:]]+node tools/design-assembly/components.mjs$" "$mk"; then
  echo "make check does not check the register with the design-assembly tool"
  exit 1
fi
before=$(git -C "$root" status --short -- . ':!design/component-registry.json')
if ! make -C "$root" gen >/dev/null 2>&1; then
  echo "make gen failed"
  exit 1
fi
after=$(git -C "$root" status --short -- . ':!design/component-registry.json')
if [ "$before" != "$after" ]; then
  echo "make gen also changed:"
  diff <(echo "$before") <(echo "$after") | grep '^>' | sed 's/^> /  /'
fi
if ! git -C "$root" diff --quiet -- design/component-registry.json; then
  echo "register differs after make gen"
  exit 1
fi
echo "registry regenerated by the design-assembly tool, identical to commit"
